// Fallback variant generator for any custom color name
export const getVariantProfile = (colorName, productTitle = '') => {
  if (!colorName) return null
  const clean = colorName.trim()
  if (COLOR_VARIANT_PROFILES[clean]) {
    return COLOR_VARIANT_PROFILES[clean]
  }

  // Case-insensitive match
  const foundKey = Object.keys(COLOR_VARIANT_PROFILES).find(
    (k) => k.toLowerCase() === clean.toLowerCase()
  )
  if (foundKey) {
    return COLOR_VARIANT_PROFILES[foundKey]
  }

  // Dynamic profile for custom colors
  return {
    title: `${clean} Custom Edition: Distinctive Character & Exclusive Appeal`,
    headline: `Tailored ${clean} aesthetic engineered for ${productTitle || 'TFiPro premium products'}.`,
    vibe: `Custom Exclusive Finish (${clean})`,
    description: `The ${clean} variant offers an exclusive visual identity carefully curated to highlight the unique lines and ergonomics of this model.`,
    stylingGuide: `Versatile and unique. Mix and match with complementary wardrobe tones to highlight the distinct ${clean} finish.`,
    dialDetail: `Crisply applied indices and balanced contrast calibrated specifically for the ${clean} edition.`,
    finishCare: `Clean gently with a soft microfiber cloth to keep the ${clean} finish looking pristine.`,
  }
}

